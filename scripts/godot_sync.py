"""Keep gdsyntax in step with the Godot release it is translated from.

gdsyntax follows one Godot tag, pinned in godot.toml. From that tag it copies
Godot's GDScript test scripts (tests/godot/<major.minor>) and its identifier
tables (src/lexer/unicode.rs), and its tokenizer and parser are translations of
the files in WATCHED.

    python scripts/godot_sync.py check [--godot DIR] [--against TAG]
        Fails when the copied files differ from the pinned tag, or when a newer
        Godot release (the latest stable by default) changed a watched file.

    python scripts/godot_sync.py update [--godot DIR] [--tag TAG]
        Copies the test scripts and tables from TAG (the latest stable by
        default) and pins it. Read the diff of the watched files it prints,
        port what changed, and run the tests.

Without --godot, the script keeps a shallow, blobless clone of Godot in
target/godot-sync (a few MB of trees; file contents are fetched on demand).
"""
import argparse
import io
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PIN = ROOT / "godot.toml"
GODOT_URL = "https://github.com/godotengine/godot.git"
TESTS = "modules/gdscript/tests/scripts"
# Editor completion tests: not about parsing, so not copied.
SKIPPED_TESTS = ("completion/",)
UNICODE_SOURCE = "core/string/char_range.cpp"
UNICODE_TARGET = ROOT / "src/lexer/unicode.rs"
# What gdsyntax is translated from. A change here between two tags means the
# tokenizer, the parser or the identifier tables may need porting.
WATCHED = [
    "modules/gdscript/gdscript_tokenizer.cpp",
    "modules/gdscript/gdscript_tokenizer.h",
    "modules/gdscript/gdscript_parser.cpp",
    "modules/gdscript/gdscript_parser.h",
    UNICODE_SOURCE,
    TESTS,
]


def git(godot, *args, binary=False):
    out = subprocess.run(
        ["git", "-C", str(godot), *args], check=True, capture_output=True
    ).stdout
    return out if binary else out.decode("utf-8")


def version_key(tag):
    """`4.7.2-stable` -> (4, 7, 2), for picking the latest release."""
    return tuple(int(n) for n in tag.removesuffix("-stable").split("."))


def series(tag):
    """The test folder a tag's scripts go in: `4.7.2-stable` -> `4.7`."""
    return ".".join(tag.removesuffix("-stable").split(".")[:2])


def latest_stable():
    out = subprocess.run(
        ["git", "ls-remote", "--tags", "--refs", GODOT_URL, "*-stable"],
        check=True, capture_output=True, text=True,
    ).stdout
    tags = re.findall(r"refs/tags/(\d+(?:\.\d+)+-stable)$", out, re.M)
    return max(tags, key=version_key)


def pinned():
    return tomllib.loads(PIN.read_text(encoding="utf-8"))["tag"]


def godot_with(godot, tags):
    """A Godot repository that has every tag in `tags`."""
    if godot is None:
        godot = ROOT / "target/godot-sync"
        if not (godot / ".git").exists():
            godot.mkdir(parents=True, exist_ok=True)
            git(godot, "init", "--quiet")
            git(godot, "remote", "add", "origin", GODOT_URL)
            git(godot, "config", "remote.origin.promisor", "true")
            git(godot, "config", "remote.origin.partialclonefilter", "blob:none")
    godot = Path(godot)
    for tag in tags:
        if subprocess.run(
            ["git", "-C", str(godot), "rev-parse", "--verify", "--quiet",
             f"refs/tags/{tag}^{{commit}}"],
            capture_output=True,
        ).returncode != 0:
            print(f"fetching Godot {tag}", file=sys.stderr)
            git(godot, "fetch", "--quiet", "--depth", "1", "--filter=blob:none",
                "origin", f"refs/tags/{tag}:refs/tags/{tag}")
    return godot


def extract_tests(godot, tag, into):
    """Godot's test scripts at `tag`, written under `into` as Godot has them."""
    archive = git(godot, "archive", "--format=tar", tag, TESTS, binary=True)
    prefix = TESTS + "/"
    with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
        for member in tar.getmembers():
            name = member.name.removeprefix(prefix)
            if not member.isfile() or name.startswith(SKIPPED_TESTS):
                continue
            path = into / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(tar.extractfile(member).read())


def unicode_tables(godot, tag):
    """src/lexer/unicode.rs as generated from Godot's tables at `tag`."""
    source = git(godot, "show", f"{tag}:{UNICODE_SOURCE}")
    unicode_version = re.search(r"Public/([0-9.]+)/ucd", source).group(1)
    out = [
        "// Generated by scripts/godot_sync.py from Godot "
        f"{tag} (Unicode {unicode_version}). Do not edit.",
        "",
    ]
    for rust, cpp in (("XID_START", "xid_start"), ("XID_CONTINUE", "xid_continue")):
        body = re.search(cpp + r"\[[^\]]*\] = \{(.*?)\};", source, re.S).group(1)
        ranges = re.findall(r"\{ (0x[0-9a-f]+), (0x[0-9a-f]+) \}", body)
        out.append(f"pub(super) static {rust}: [(u32, u32); {len(ranges)}] = [")
        out += [f"    ({a}, {b})," for a, b in ranges]
        out.append("];")
        out.append("")
    return "\n".join(out)


def files_under(folder):
    return {
        p.relative_to(folder).as_posix(): p.read_bytes()
        for p in folder.rglob("*")
        if p.is_file()
    }


def vendored_problems(godot, tag):
    """How the copied files differ from Godot's at `tag`."""
    problems = []
    folder = ROOT / "tests/godot" / series(tag)
    with tempfile.TemporaryDirectory() as tmp:
        extract_tests(godot, tag, Path(tmp))
        want, have = files_under(Path(tmp)), files_under(folder) if folder.exists() else {}
    for name in sorted(want.keys() | have.keys()):
        where = f"tests/godot/{series(tag)}/{name}"
        if name not in have:
            problems.append(f"{where}: missing (Godot {tag} has it)")
        elif name not in want:
            problems.append(f"{where}: not in Godot {tag}")
        elif want[name] != have[name]:
            problems.append(f"{where}: differs from Godot {tag}")
    tables = UNICODE_TARGET.read_text(encoding="utf-8")
    if tables != unicode_tables(godot, tag):
        problems.append(f"src/lexer/unicode.rs: not generated from Godot {tag}")
    return problems


def watched_changes(godot, old, new):
    """What changed between two tags in the files gdsyntax follows: a diffstat
    of the sources, and a count of the test scripts."""
    sources = [w for w in WATCHED if w != TESTS]
    lines = git(godot, "diff", "--stat=100", old, new, "--", *sources).splitlines()
    tests = [
        name for name in git(godot, "diff", "--name-only", old, new, "--", TESTS).split()
        if not name.removeprefix(TESTS + "/").startswith(SKIPPED_TESTS)
    ]
    if tests:
        lines = lines[:-1] if lines else []
        lines.append(f" {len(tests)} files in {TESTS}")
    return "\n".join(lines)


def check(args):
    tag = pinned()
    against = args.against or latest_stable()
    godot = godot_with(args.godot, [tag, against])
    failed = False

    problems = vendored_problems(godot, tag)
    if problems:
        failed = True
        print(f"The copied files do not match Godot {tag}, which godot.toml pins:")
        print("\n".join(f"  {p}" for p in problems))
        print("Run `just godot-sync update --tag " + tag + "` to copy them again.")
    else:
        print(f"The copied test scripts and tables match Godot {tag}.")

    if against == tag:
        print(f"Godot {against} is the pinned tag.")
    else:
        changes = watched_changes(godot, tag, against)
        if changes:
            failed = True
            print(f"\nGodot {against} changed what gdsyntax is translated from "
                  f"since {tag}:\n{changes}")
            print(f"Run `just godot-sync update --tag {against}`, port the "
                  "changes, and run the tests.")
        else:
            print(f"Godot {against} changes nothing gdsyntax follows since {tag}; "
                  f"`just godot-sync update --tag {against}` moves the pin.")
    return 1 if failed else 0


def update(args):
    old = pinned()
    tag = args.tag or latest_stable()
    godot = godot_with(args.godot, [old, tag])

    folder = ROOT / "tests/godot" / series(tag)
    if folder.exists():
        shutil.rmtree(folder)
    extract_tests(godot, tag, folder)
    UNICODE_TARGET.write_text(unicode_tables(godot, tag), encoding="utf-8", newline="\n")
    PIN.write_text(
        PIN.read_text(encoding="utf-8").replace(f'tag = "{old}"', f'tag = "{tag}"'),
        encoding="utf-8", newline="\n",
    )
    print(f"Copied Godot {tag}'s test scripts to tests/godot/{series(tag)} "
          "and regenerated src/lexer/unicode.rs.")
    if series(tag) != series(old):
        print(f"This is a new Godot series: point the tests at {series(tag)} "
              f"(grep for \"{series(old)}\") and update the versions in the docs.")
    if old != tag:
        changes = watched_changes(godot, old, tag)
        if changes:
            print(f"\nWhat changed in the files gdsyntax is translated from:\n{changes}")
            print(f"See it with: git -C {godot} diff {old} {tag} -- "
                  + " ".join(WATCHED))
        else:
            print(f"Nothing gdsyntax is translated from changed since {old}.")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)
    for name, helps in (
        ("check", "--against TAG: compare with this tag instead of the latest stable"),
        ("update", "--tag TAG: copy from this tag instead of the latest stable"),
    ):
        p = sub.add_parser(name)
        p.add_argument("--godot", type=Path, help="an existing Godot checkout")
        flag = "--against" if name == "check" else "--tag"
        p.add_argument(flag, help=helps.split(": ", 1)[1])
    args = parser.parse_args()
    return check(args) if args.command == "check" else update(args)


if __name__ == "__main__":
    sys.exit(main())
